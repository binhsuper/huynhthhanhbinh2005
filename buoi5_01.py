# YÊU CẦU 3: Ý tưởng của các hàm gợi ý
# - Luật kết hợp: mỗi user là 1 giao dịch gồm các phim chấm >= 4. Tìm luật A -> B (support,
#   confidence, lift). Với user cần gợi ý, lấy các luật có vế trái A nằm hết trong phim user
#   đã thích, phim ở vế phải B mà user chưa xem là ứng viên. Điểm = confidence trung bình x
#   lift trung bình của các luật dẫn tới phim đó, lấy top n.
# - Phân cụm: PCA giảm chiều rồi KMeans gom user có gu giống nhau. Với user cần gợi ý, xác định
#   cụm của họ rồi lấy các phim điểm trung bình cao nhất trong cụm mà họ chưa xem. Ý tưởng:
#   người cùng nhóm sở thích thường thích phim giống nhau.
# - SVD/NMF: tách ma trận rating thành ma trận user và ma trận phim qua các yếu tố ẩn. Học bằng
#   SGD sao cho điểm dự đoán gần điểm thật ở các ô đã có rating. Sau đó dự đoán điểm cho mọi
#   phim user chưa xem và chọn phim có điểm dự đoán cao nhất. NMF giống SVD nhưng bắt các giá
#   trị trong hai ma trận phải không âm.

