    top_movies = list(cluster_preferences[cluster]['top_movies'].index)
    watched = set(ratings_df[ratings_df['user_id'] == user_id]['item_id'].values)

    recommendations = []
    for movie_id in top_movies:
        if movie_id not in watched and len(recommendations) < n:
            recommendations.append({'movie_id': int(movie_id),
                                    'title': get_movie_title(movie_id),
                                    'avg_rating': cluster_preferences[cluster]['top_movies'][movie_id],
                                    'method': 'clustering'})
    return recommendations

