# Xây dựng hàm gợi ý bằng luật kết hợp
def recommend_by_association(user_id, rules, ratings_df, n=10):
    if len(rules) == 0:
        return []
    user_ratings = ratings_df[ratings_df['user_id'] == user_id]
    liked_movies = user_ratings[user_ratings['rating'] >= 4]['item_id'].tolist()

    if len(liked_movies) < 2:
        return []
    liked_set = set(liked_movies)

    candidate_rules = []
    for _, rule in rules.iterrows():
        antecedents = set(rule['antecedents'])
        if antecedents.issubset(liked_set):
            for cons in rule['consequents']:
                if cons not in liked_set:
                    candidate_rules.append({'movie_id': cons,
                                            'confidence': rule['confidence'],
                                            'lift': rule['lift']})
    if not candidate_rules:
        return []

    df_rec = pd.DataFrame(candidate_rules)
    scores = df_rec.groupby('movie_id').agg({'confidence': 'mean', 'lift': 'mean'}).reset_index()
    scores['score'] = scores['confidence'] * scores['lift']
    scores = scores.sort_values('score', ascending=False).head(n)

    return [{'movie_id': int(row['movie_id']),
             'title': get_movie_title(row['movie_id']),
             'score': row['score'],
             'method': 'association'} for _, row in scores.iterrows()]

