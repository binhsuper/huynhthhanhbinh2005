# Chuẩn bị dữ liệu cho Surprise
from surprise import Dataset, Reader, SVD, NMF
from surprise.model_selection import train_test_split
from surprise import accuracy

reader = Reader(rating_scale=(1, 5))
data = Dataset.load_from_df(ratings[['user_id', 'item_id', 'rating']], reader)
trainset, testset = train_test_split(data, test_size=0.2, random_state=42)

# Huấn luyện SVD
svd_factors = [10, 20, 30, 50]
svd_results = {}

for n_factors in svd_factors:
    model = SVD(n_factors=n_factors, n_epochs=20, random_state=42)
    model.fit(trainset)
    predictions = model.test(testset)
    rmse = accuracy.rmse(predictions, verbose=False)
    mae = accuracy.mae(predictions, verbose=False)
    svd_results[n_factors] = {'model': model, 'rmse': rmse, 'mae': mae}
    print(f"SVD n_factors={n_factors}: RMSE={rmse:.4f}, MAE={mae:.4f}")

# Chọn mô hình SVD tốt nhất
best_svd_n = min(svd_results, key=lambda x: svd_results[x]['rmse'])
best_svd = svd_results[best_svd_n]['model']
print(f"SVD tốt nhất: n_factors={best_svd_n}, RMSE={svd_results[best_svd_n]['rmse']:.4f}")

# Huấn luyện NMF và chọn mô hình tốt nhất
nmf_factors = [10, 15, 20, 30]
nmf_results = {}

for n_factors in nmf_factors:
    model = NMF(n_factors=n_factors, n_epochs=50, random_state=42)
    model.fit(trainset)
    predictions = model.test(testset)
    rmse = accuracy.rmse(predictions, verbose=False)
    mae = accuracy.mae(predictions, verbose=False)
    nmf_results[n_factors] = {'model': model, 'rmse': rmse, 'mae': mae}
    print(f"NMF n_factors={n_factors}: RMSE={rmse:.4f}, MAE={mae:.4f}")

best_nmf_n = min(nmf_results, key=lambda x: nmf_results[x]['rmse'])
best_nmf = nmf_results[best_nmf_n]['model']
print(f"NMF tốt nhất: n_factors={best_nmf_n}, RMSE={nmf_results[best_nmf_n]['rmse']:.4f}")

# Xây dựng hàm gợi ý Matrix Factorization
def recommend_by_matrix_factorization(user_id, model, ratings_df, n=10):
    watched = set(ratings_df[ratings_df['user_id'] == user_id]['item_id'].values)
    all_movies = ratings_df['item_id'].unique()
    # SỬA: bỏ [:200] (trước đây chỉ xét 200 phim đầu nên bỏ sót ứng viên)
    unwatched = [m for m in all_movies if m not in watched]

    predictions = [(m, model.predict(user_id, m).est) for m in unwatched]
    predictions.sort(key=lambda x: x[1], reverse=True)

    return [{'movie_id': int(m), 'title': get_movie_title(m), 'predicted_rating': s,
             'method': 'SVD' if isinstance(model, SVD) else 'NMF'}
            for m, s in predictions[:n]]

