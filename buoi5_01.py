# Sinh luật kết hợp
def make_rules(freq_itemsets, n_transactions, min_lift=1.0):
    """association_rules tương thích cả mlxtend bản mới (cần num_itemsets) lẫn bản cũ."""
    try:
        return association_rules(freq_itemsets, num_itemsets=n_transactions,
                                 metric="lift", min_threshold=min_lift)
    except TypeError:
        return association_rules(freq_itemsets, metric="lift", min_threshold=min_lift)

